#!/usr/bin/env node
// Writes truthful, build-time impact numbers into urban/frontend/about.html.
//
// Every number on the About/Impact page is counted from the content folder at
// build time — never typed by hand — so the page can't drift from reality.
// The block between <!-- impact:start --> and <!-- impact:end --> is
// regenerated in place; everything else in the file is left untouched.
// Idempotent: running it twice produces no diff. CI runs it before deploy.
//
// Usage: node scripts/generate-impact-stats.mjs [--check]
//   --check  exit 1 if about.html is out of date (no write)

import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const LEVELS = join(ROOT, "content/levels");
const EXAMS = join(ROOT, "content/exams");
const ABOUT = join(ROOT, "urban/frontend/about.html");

const readJson = (p) => JSON.parse(readFileSync(p, "utf8"));
const questionsOf = (j) =>
  Array.isArray(j.questions) ? j.questions
  : Array.isArray(j.levels) ? j.levels.flatMap((l) => l.questions || [])
  : [];

// K-12 banks are named <class>-<subject>.json (class 1-12). Skill files used by
// the rural early-literacy build (numbers.json, letters.json, ...) are not
// class banks and are not counted here.
let levelQuestions = 0;
const classes = new Set();
const subjects = new Set();
const languages = new Set();
for (const f of readdirSync(LEVELS)) {
  const m = f.match(/^(\d{1,2})-(.+)\.json$/);
  if (!m) continue;
  const qs = questionsOf(readJson(join(LEVELS, f)));
  if (!qs.length) continue;
  classes.add(Number(m[1]));
  subjects.add(m[2]);
  levelQuestions += qs.length;
  for (const q of qs) for (const k of Object.keys(q.prompt || {})) languages.add(k);
}

let examQuestions = 0;
let examBanks = 0;
for (const exam of readdirSync(EXAMS)) {
  const dir = join(EXAMS, exam);
  if (!statSync(dir).isDirectory()) continue;
  for (const f of readdirSync(dir)) {
    if (!f.endsWith(".json")) continue;
    const n = questionsOf(readJson(join(dir, f))).length;
    if (n) { examBanks++; examQuestions += n; }
  }
}

const classList = [...classes].sort((a, b) => a - b);
const fmt = (n) => n.toLocaleString("en-IN");
// Round down to a friendly floor so the claim stays true as banks shift a bit.
const floor = (n, step) => Math.floor(n / step) * step;
const stats = [
  [`${fmt(floor(levelQuestions, 100))}+`, "practice questions, Class 1–12"],
  [`${fmt(floor(examQuestions, 10))}+`, `exam-prep questions across ${examBanks} subjects`],
  [String(languages.size), "languages, English and 12 Indian languages"],
  [`${classList[0]}–${classList[classList.length - 1]}`, `classes, ${subjects.size} subjects`],
];

const block = [
  "<!-- impact:start (generated by scripts/generate-impact-stats.mjs — do not edit by hand) -->",
  '  <div class="impact" role="list">',
  ...stats.map(([num, label]) =>
    `    <div class="impact-stat" role="listitem"><span class="impact-num">${num}</span><span class="impact-label">${label}</span></div>`),
  "  </div>",
  "  <!-- impact:end -->",
].join("\n");

const html = readFileSync(ABOUT, "utf8");
const re = /<!-- impact:start[\s\S]*?<!-- impact:end -->/;
if (!re.test(html)) {
  console.error("about.html has no <!-- impact:start --> … <!-- impact:end --> block");
  process.exit(1);
}
const next = html.replace(re, block);
if (process.argv.includes("--check")) {
  if (next !== html) { console.error("about.html impact numbers are stale; run node scripts/generate-impact-stats.mjs"); process.exit(1); }
  console.log("about.html impact numbers are up to date");
} else {
  if (next !== html) writeFileSync(ABOUT, next);
  console.log({ levelQuestions, examQuestions, examBanks, languages: languages.size, classes: classList.join(","), subjects: subjects.size });
}
