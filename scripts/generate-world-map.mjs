#!/usr/bin/env node
// Builds urban/frontend/js/world-land.js: a lightweight world map for the
// "Where are you learning from?" screen.
//
// Land outlines ONLY, with no country borders: borders are disputed in
// several places (including India's), and a learning app should never take a
// side. Countries appear as pins placed at a point inside them.
//
// Data: Natural Earth 1:110m land (public domain), via the `world-atlas`
// npm package (ISC). Projection: Natural Earth 1.
//
// One-time tooling (not a site dependency):
//   npm i --no-save world-atlas@2.0.2 topojson-client@3.1.0 d3-geo@3.1.1
//   node scripts/generate-world-map.mjs
// Set MAPGEN_DIR to another folder that holds those node_modules if needed.

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { createRequire } from "module";
import { COUNTRIES } from "../content/countries.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const req = createRequire(path.join(process.env.MAPGEN_DIR || ROOT, "noop.js"));
const { feature } = req("topojson-client");
const { geoNaturalEarth1, geoPath } = req("d3-geo");
const land = req("world-atlas/land-110m.json");

const W = 1000, H = 500;
const geo = feature(land, land.objects.land);
// Drop Antarctica (south of 60°S) so the populated world fills the frame.
geo.features = geo.features.map((f) => ({
  ...f,
  geometry: {
    ...f.geometry,
    coordinates: f.geometry.coordinates.filter((poly) => poly[0].some(([, lat]) => lat > -60)),
  },
}));
const projection = geoNaturalEarth1().fitExtent([[8, 8], [W - 8, H - 8]], geo);
const d = geoPath(projection).digits(0)(geo);

const pins = Object.fromEntries(
  COUNTRIES.map((c) => {
    const [x, y] = projection([c.lon, c.lat]);
    return [c.code, [Math.round(x), Math.round(y)]];
  }),
);

const out = `// Generated by scripts/generate-world-map.mjs — do not edit by hand.
// Natural Earth 1:110m land (public domain) via world-atlas (ISC). Land only,
// no borders. Pins are projected country points on the same ${W}×${H} canvas.
export const MAP_W = ${W};
export const MAP_H = ${H};
export const LAND_PATH = ${JSON.stringify(d)};
export const PINS = ${JSON.stringify(pins)};
`;
const file = path.join(ROOT, "urban/frontend/js/world-land.js");
fs.writeFileSync(file, out);
console.log(`world-land.js: ${(out.length / 1024).toFixed(1)} KB, ${Object.keys(pins).length} pins`);
